// Pure: build REPORT.md for stage 04-native from its index.

const mb = (n) => (n >= 1048576 ? `${(n / 1048576).toFixed(1)} MB` : `${(n / 1024).toFixed(0)} KB`);
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const FIRST_PARTY = new Set(['electron-host', 'voyager-helper', 'installer-helper', 'native-module']);

function product(r) {
  const s = r.version?.strings ?? {};
  return [s.ProductName, s.FileVersion ?? r.version?.fileVersion].filter(Boolean).join(' ') || '';
}

export function buildReport(index, limits) {
  const bins = index.binaries.filter((r) => !r.error);
  const failed = index.binaries.filter((r) => r.error);
  const L = [];
  L.push('# Voyager: native binaries report', '');
  L.push('Generated by stage `04-native` from `out/01-installer/` and `out/02-asar/`. Static analysis only; see Limits.', '');

  const byRole = {};
  for (const r of bins) (byRole[r.role] ??= []).push(r);
  const copies = bins.reduce((n, r) => n + r.copies.length, 0);
  L.push('## Overview', '');
  L.push(`- ${bins.length} unique PE binaries (${copies} further identical copies), ${mb(bins.reduce((n, r) => n + r.size, 0))} total.`);
  L.push(`- By role: ${Object.entries(byRole).sort().map(([k, v]) => `${k} ${v.length}`).join(', ')}.`);
  L.push(`- Authenticode signature present: ${bins.filter((r) => r.signature).length} of ${bins.length}.`);
  L.push(`- High-entropy executable sections (possible packing): ${bins.filter((r) => r.packedSections.length).length}.`);
  L.push(`- .NET assemblies: ${bins.filter((r) => r.dotnet).length}. Parse failures: ${failed.length}.`, '');

  L.push('## First-party binaries', '', '| path | role | size | arch | signed by | version | packed | capabilities |', '|---|---|---|---|---|---|---|---|');
  const fp = bins.filter((r) => FIRST_PARTY.has(r.role)).sort((a, b) => b.size - a.size);
  for (const r of fp) {
    L.push(`| ${esc(r.path)} | ${r.role} | ${mb(r.size)} | ${r.machine} ${r.isDll ? 'dll' : r.subsystem} | ${esc(r.signature ? r.signature.signer ?? '(unknown)' : 'unsigned')} | ${esc(product(r))} | ${r.packedSections.join(', ') || 'no'} | ${Object.keys(r.capabilities).join(', ')} |`);
  }
  L.push('');

  for (const r of fp) {
    L.push(`### ${basenameOf(r.path)}`, '');
    L.push(`- Path: \`${r.path}\`${r.copies.length ? ` (+${r.copies.length} identical: ${r.copies.map((c) => `\`${c}\``).join(', ')})` : ''}`);
    L.push(`- ${r.format} ${r.machine}, ${r.isDll ? 'DLL' : r.subsystem}, linked ${r.timestampIso ?? `(timestamp ${r.timestamp})`}, sha256 \`${r.sha256}\``);
    L.push(`- Hardening: ${r.dllCharacteristics.join(', ') || 'none'}`);
    if (r.toolchains?.length) L.push(`- Built with: ${r.toolchains.join(', ')}`);
    const vs = r.version?.strings ?? {};
    if (Object.keys(vs).length) L.push(`- Version info: ${Object.entries(vs).filter(([, v]) => v).map(([k, v]) => `${k}=${esc(v)}`).join('; ')}`);
    if (r.signature) L.push(`- Signature (not verified): signer ${esc(r.signature.signer ?? '?')}; chain CNs: ${r.signature.commonNames.map(esc).join(', ')}`);
    else L.push('- Signature: none');
    if (r.pdb) L.push(`- PDB: \`${esc(r.pdb)}\``);
    L.push(`- Sections: ${r.sections.map((s) => `${s.name} (${mb(s.rawSize)}, H=${s.entropy})`).join(', ')}`);
    const imp = [...r.imports, ...r.delayImports];
    L.push(`- Imports: ${r.importCount} functions from ${imp.length} DLLs: ${imp.map((d) => d.dll).join(', ') || 'none'}`);
    if (r.exports) L.push(`- Exports: ${r.exports.functions} (${r.exports.names.slice(0, 15).join(', ')}${r.exports.names.length > 15 ? ', ...' : ''})`);
    for (const [cap, ev] of Object.entries(r.capabilities)) L.push(`  - ${cap}: ${ev.slice(0, 8).join(', ')}`);
    const st = r.strings.interesting;
    for (const cat of ['url', 'pipe', 'ipc', 'registry', 'shell', 'path', 'envvar']) {
      const v = st[cat];
      if (v?.length) L.push(`- Strings/${cat} (${v.length}${v.length >= 150 ? '+' : ''}): ${v.slice(0, 12).map((s) => `\`${esc(s.slice(0, 120))}\``).join(', ')}`);
    }
    L.push('');
  }

  L.push(...embeddedSection(bins));

  L.push('## Bundled tools and runtime', '');
  const eng = index.engines?.manifest?.engines;
  if (eng) {
    L.push('Engines (`resources/engines/engines-manifest.json`):', '', '| engine | version | binary | source |', '|---|---|---|---|');
    for (const [k, v] of Object.entries(eng)) L.push(`| ${k} | ${esc(v.version ?? '-')} | ${esc(v.binary ?? v.skipped ?? '-')} | ${esc(v.url ?? '-')} |`);
    L.push('');
  }
  if (index.engines?.tools?.length) L.push(`Native tools under \`resources/voyager/native/\`: ${index.engines.tools.map((t) => `\`${t}\``).join(', ')}.`, '');
  const third = bins.filter((r) => !FIRST_PARTY.has(r.role)).sort((a, b) => b.size - a.size);
  L.push('| path | role | size | product | signed by | packed |', '|---|---|---|---|---|---|');
  for (const r of third) L.push(`| ${esc(r.path)}${r.copies.length ? ` (+${r.copies.length})` : ''} | ${r.role} | ${mb(r.size)} | ${esc(product(r))} | ${esc(r.signature ? r.signature.signer ?? '?' : 'unsigned')} | ${r.packedSections.join(', ') || 'no'} |`);
  L.push('');

  if (failed.length) {
    L.push('## Parse failures', '');
    for (const r of failed) L.push(`- ${esc(r.path)}: ${esc(r.error)}`);
    L.push('');
  }
  L.push('## Limits', '', ...limits.map((l) => `- ${l}`), '');
  return L.join('\n');
}

function basenameOf(p) { return p.split('/').pop(); }

const kind = (p) => (/\.(m|c)?js$/.test(p) ? 'js' : (p.match(/\.([a-z0-9]+)$/i)?.[1] ?? 'other').toLowerCase());

/** Report lines for Bun standalone apps and Rust build provenance. */
export function embeddedSection(bins) {
  const L = ['## Embedded payloads', ''];
  const bun = bins.filter((r) => r.bun);
  L.push(`### Bun standalone executables (${bun.length})`, '');
  if (!bun.length) L.push('None found.', '');
  for (const r of bun) {
    const b = r.bun;
    /** @type {Record<string, {n: number, bytes: number}>} */
    const byKind = {};
    for (const m of b.modules) { const k = kind(m.path); byKind[k] ??= { n: 0, bytes: 0 }; byKind[k].n++; byKind[k].bytes += m.size; }
    L.push(`**${esc(basenameOf(r.path))}**: ${b.modules.length} embedded files (${mb(b.bytes)}), entry point \`${esc(b.entryPoint ?? '?')}\`${b.userAgent ? `, identifies as \`${esc(b.userAgent)}\`` : ''}.`, '');
    L.push(`- Exec argv baked in: \`${esc(b.execArgv || '(none)')}\``);
    L.push(`- By type: ${Object.entries(byKind).sort((x, y) => y[1].bytes - x[1].bytes).map(([k, v]) => `${k} ${v.n} (${mb(v.bytes)})`).join(', ')}`);
    L.push(`- Bytecode: ${b.modules.some((m) => m.bytecodeBytes) ? 'present' : 'none'}; source maps: ${b.modules.some((m) => m.sourcemapBytes) ? 'present' : 'none'}`);
    L.push(`- Extracted to \`out/04-native/${esc(b.extractedTo)}/\``);
    const named = b.modules.filter((m) => !/^chunk-[a-z0-9]+\.js$/.test(m.path)).sort((x, y) => y.size - x.size);
    if (named.length) L.push(`- Named (non-chunk) files: ${named.slice(0, 30).map((m) => `\`${esc(m.path)}\` (${mb(m.size)})`).join(', ')}${named.length > 30 ? ', ...' : ''}`);
    L.push('');
  }
  const rust = bins.filter((r) => r.rust && (r.rust.crates.length || r.rust.sourceCount)).sort((a, b) => b.rust.sourceCount - a.rust.sourceCount || b.rust.crates.length - a.rust.crates.length);
  L.push(`### Rust build provenance (${rust.length} binaries)`, '', 'From build paths left in panic/debug strings: CI checkout, first-party crates (workspace-relative source files) and crates.io / git dependencies.', '');
  if (rust.length) {
    L.push('| binary | CI repo | first-party sources | first-party crates | deps (crates.io / git) | rustc |', '|---|---|---|---|---|---|');
    for (const r of rust) {
      const x = r.rust;
      const roots = x.sourceRoots.slice(0, 12).map((s) => `${s.root.replace(/^crates\//, '')} (${s.files})`).join(', ');
      L.push(`| ${esc(basenameOf(r.path))} | ${x.ciRepos.join(', ') || '-'} | ${x.sourceCount} | ${esc(roots) || '-'}${x.sourceRoots.length > 12 ? ', ...' : ''} | ${x.crates.length} / ${x.git.length ? x.git.map((g) => `${g.name}@${g.revs.join(',')}`).join(', ') : '0'} | ${x.rustc.map((c) => c.slice(0, 12)).join(', ') || '-'} |`);
    }
    L.push('');
    const NOTABLE = /^(tokio|axum|hyper|reqwest|tonic|serde_json|whisper-rs|ort|candle-core|wgpu|cpal|symphonia|rubato|ffmpeg-next|ffmpeg-sys-next|cranelift-codegen|wasmtime|rusqlite|sqlx|windows|tauri|napi|uniffi|keyring|portable-pty|rustls|openssl|ring|image|lofty|realfft|rustfft|midly|vst3|clap-sys|tree-sitter|notify)$/;
    for (const r of rust) {
      const notable = r.rust.crates.filter((c) => NOTABLE.test(c.name));
      if (notable.length) L.push(`- ${esc(basenameOf(r.path))} notable deps: ${notable.map((c) => `${c.name} ${c.versions.join('/')}`).join(', ')}`);
    }
    L.push('');
  } else L.push('None found.', '');
  return L;
}
