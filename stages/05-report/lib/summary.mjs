// @ts-check
// Pure: the cross-stage summary of Voyager, built from the outputs of stages 01-04
// plus evidence probes (literal/regex hits with file and offset) in the Electron main bundle.

const mb = (/** @type {number} */ n) => (n >= 1048576 ? `${(n / 1048576).toFixed(1)} MB` : `${(n / 1024).toFixed(0)} KB`);
const esc = (/** @type {unknown} */ s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const base = (/** @type {string} */ p) => p.split('/').pop() ?? p;

/**
 * Architecture claims checked against the code. A claim is reported only when its pattern matches.
 * @type {{ id: string, claim: string, re: RegExp }[]}
 */
export const PROBES = [
  { id: 'backend-node-mode', claim: 'The backend runs as a separate child process: the Electron binary re-launched in Node mode (`ELECTRON_RUN_AS_NODE=1`).', re: /ELECTRON_RUN_AS_NODE:\s*"1"/ },
  { id: 'bootstrap-fd', claim: 'The backend receives its startup configuration over an inherited file descriptor (`--bootstrap-fd 3`), not on the command line.', re: /"--bootstrap-fd",\s*"3"/ },
  { id: 'server-asar-root', claim: 'On packaged Windows builds the backend root is `resources/server.asar`.', re: /path\.join\([\w.]+,\s*"server\.asar"\)/ },
  { id: 'backend-wsl', claim: 'The backend can alternatively run inside WSL (a Linux build launched through `wsl --exec`).', re: /runningDistro|"--exec",\s*"env"/ },
  { id: 'custom-protocol', claim: 'Desktop UI assets are served from a custom privileged protocol handled in the main process (`protocol.handle`), with a generated Content-Security-Policy.', re: /electron\.protocol\.handle\(input\.scheme|makeDesktopContentSecurityPolicy/ },
  { id: 'window-open-deny', claim: 'New windows are refused by default (`setWindowOpenHandler(() => ({ action: "deny" }))`) and in-page navigation is blocked on helper windows.', re: /setWindowOpenHandler\(\(\)\s*=>\s*\(\{\s*action:\s*"deny"\s*\}\)\)/ },
  { id: 'dictation-sidecar', claim: 'Dictation is a sidecar (`voyager-dictation`) speaking a framed binary protocol on stdin (type byte + u32 LE length + payload) and JSON lines on stdout.', re: /Wire format of `voyager-dictation`/ },
  { id: 'resource-monitor', claim: 'Resource usage is sampled by a native helper (`voyager-resource-monitor`) whose path is passed to the backend.', re: /voyager-resource-monitor\.exe/ },
  { id: 'deep-link', claim: 'The app registers itself as the OS handler for its URL scheme (`setAsDefaultProtocolClient`).', re: /setAsDefaultProtocolClient\(/ },
  { id: 'crash-owners', claim: 'Crash reporting attributes child-process crashes to bundled tools (ffmpeg/ffprobe, api-models, bun, voyager-video, blender).', re: /"ffmpeg",\s*"ffprobe",\s*"api-models",\s*"bun",\s*"voyager-video"/ },
];

/**
 * Run the probes over named sources.
 * @param {{ file: string, code: string }[]} sources
 */
export function runProbes(sources) {
  return PROBES.map((p) => {
    for (const s of sources) {
      const m = p.re.exec(s.code);
      if (m) return { id: p.id, claim: p.claim, file: s.file, offset: m.index };
    }
    return { id: p.id, claim: p.claim, file: null, offset: -1 };
  });
}

/**
 * @param {{
 *   manifest: any, updateFeed: Record<string,string>|null, appPkg: any, serverPkg: any,
 *   js: { index: any, map: any } | null, native: any | null, probes: ReturnType<typeof runProbes>,
 * }} d
 */
export function buildSummary(d) {
  const L = ['# Voyager: reverse-engineering summary', ''];
  L.push('Generated by stage `05-report` from the outputs of stages 01-04 (`out/manifest.json`, `out/03-js/map.json`, `out/04-native/index.json`, package manifests). Detail lives in `out/03-js/REPORT.md` and `out/04-native/REPORT.md`.', '');

  // Identity
  const bins = (d.native?.binaries ?? []).filter((/** @type {any} */ r) => !r.error);
  const host = bins.find((/** @type {any} */ r) => r.role === 'electron-host' && !/uninstall/i.test(r.path));
  const chrome = host?.strings?.interesting?.toolchain?.map((/** @type {string} */ s) => /Chrome\/([\d.]+) Electron\/([\d.]+)/.exec(s)).find(Boolean);
  const e01 = d.manifest?.entries?.find((/** @type {any} */ e) => e.stage === '01-installer');
  L.push('## Identity', '');
  L.push('| field | value |', '|---|---|');
  L.push(`| Product | ${esc(host?.version?.strings?.ProductName ?? d.appPkg?.productName ?? d.appPkg?.name ?? '?')} ${esc(d.appPkg?.version ?? host?.version?.strings?.FileVersion ?? '')} |`);
  if (chrome) L.push(`| Runtime | Electron ${chrome[2]} (Chromium ${chrome[1]}) |`);
  if (host) L.push(`| Host binary | \`${esc(base(host.path))}\`, ${host.machine}, linked ${esc(host.timestampIso)}, Authenticode: ${host.signature ? esc(host.signature.signer ?? 'present') : 'none'} |`);
  if (d.updateFeed) L.push(`| Update feed | ${esc(d.updateFeed.provider)} \`${esc(d.updateFeed.owner)}/${esc(d.updateFeed.repo)}\` (electron-updater) |`);
  const inst = (e01?.notes ?? []).find((/** @type {string} */ n) => /nsis/i.test(n));
  if (inst) L.push(`| Installer | ${esc(inst)} |`);
  if (d.appPkg) L.push(`| Packages | \`${esc(d.appPkg.name)}\` (app.asar, main \`${esc(d.appPkg.main)}\`)${d.serverPkg ? `, \`${esc(d.serverPkg.name)}\` (server.asar)` : ''} |`);
  L.push('');

  // Architecture
  L.push('## Architecture', '');
  const found = d.probes.filter((p) => p.file);
  if (found.length) {
    for (const p of found) L.push(`- ${p.claim} _(evidence: \`${esc(p.file)}\` @ ${p.offset})_`);
  } else L.push('- No architecture probes matched (main bundle missing or changed).');
  const missing = d.probes.filter((p) => !p.file);
  if (missing.length) L.push('', `Probes with no match (claims not made): ${missing.map((p) => `\`${p.id}\``).join(', ')}.`);
  L.push('');

  const map = d.js?.map;
  const s = map?.surface;
  if (map) {
    const fp = Object.entries(map.firstParty ?? {});
    const byArchive = /** @type {Record<string, number>} */ ({});
    for (const [k, v] of fp) byArchive[k.split(':')[0]] = (byArchive[k.split(':')[0]] ?? 0) + /** @type {any[]} */ (v).length;
    L.push('### First-party code', '');
    L.push(`- ${fp.length} first-party workspace packages/apps recovered from bundle regions (${Object.entries(byArchive).map(([a, n]) => `${a}: ${n} source modules`).join(', ')}).`);
    const biggest = fp.sort((a, b) => /** @type {any[]} */ (b[1]).length - /** @type {any[]} */ (a[1]).length).slice(0, 10);
    L.push(`- Largest: ${biggest.map(([k, v]) => `\`${esc(k)}\` (${/** @type {any[]} */ (v).length})`).join(', ')}.`);
    L.push(`- ${map.packages?.length ?? 0} third-party npm packages shipped in node_modules.`, '');
  }

  // Interfaces
  if (s) {
    const ws = s.rpcTables?.[0];
    const serve = s.routes.filter((/** @type {any} */ r) => r.kind === 'serve');
    const bridge = s.bridges.find((/** @type {any} */ b) => b.members.length) ;
    L.push('## Interfaces between the parts', '');
    L.push('| boundary | mechanism | size | where to look |', '|---|---|---|---|');
    if (bridge) L.push(`| web UI -> Electron main | \`window.${esc(bridge.api)}\` (contextBridge) over IPC | ${bridge.members.length} members, ${Object.keys(map.electron.ipcChannels).length} IPC channels | 03-js REPORT: contextBridge APIs, IPC channels |`);
    if (ws) L.push(`| web UI -> backend | RPC method table \`${esc(ws.name)}\`${serve.some((/** @type {any} */ r) => r.path === '/ws') ? ' over WebSocket `GET /ws`' : ''} | ${ws.methods.length} methods | 03-js REPORT: RPC method tables |`);
    L.push(`| backend HTTP | local HTTP server | ${serve.length} served routes | 03-js REPORT: HTTP endpoints served |`);
    L.push(`| backend -> agents/tools | JSON-RPC \`method: "a/b"\` messages (agent app-server, MCP) | ${Object.keys(s.jsonRpc).length} methods | 03-js REPORT: JSON-RPC methods |`);
    L.push(`| app -> network | outbound HTTP | ${Object.keys(map.network.hosts).length} hosts, ${s.routes.filter((/** @type {any} */ r) => r.kind === 'call').length} API paths | 03-js REPORT: Network endpoints, Outbound HTTP API calls |`);
    L.push(`| JS -> native code | Node native addons | ${s.nativeAddons.files.length} .node files | 03-js REPORT: Native addons; 04-native REPORT |`);
    L.push('');
    const topHosts = Object.entries(map.network.hosts).filter(([h]) => h !== '(invalid)').sort((a, b) => /** @type {any[]} */ (b[1]).length - /** @type {any[]} */ (a[1]).length).slice(0, 15);
    if (topHosts.length) L.push(`Most referenced hosts: ${topHosts.map(([h, v]) => `\`${esc(h)}\` (${/** @type {any[]} */ (v).length})`).join(', ')}.`, '');
  }

  // Components
  if (bins.length) {
    L.push('## Native components', '');
    L.push('| component | role | built with | signed by | what it is |', '|---|---|---|---|---|');
    const interesting = bins.filter((/** @type {any} */ r) => ['electron-host', 'voyager-helper', 'native-module'].includes(r.role) || r.bun || r.rust?.sourceCount)
      .sort((/** @type {any} */ a, /** @type {any} */ b) => b.size - a.size);
    for (const r of interesting) {
      const what = r.bun ? `Bun standalone app${r.bun.userAgent ? ` identifying as \`${esc(r.bun.userAgent)}\`` : ''}, ${r.bun.modules.length} embedded files`
        : r.rust?.sourceRoots?.length ? `${r.rust.ciRepos?.length ? `CI repo \`${esc(r.rust.ciRepos.join(', '))}\`; ` : ''}${rustCrates(r.rust)}; ${r.rust.crates.length} crates.io deps`
          : esc(r.version?.strings?.FileDescription ?? '');
      const built = r.bun ? 'Bun standalone (JS), Rust deps' : esc((r.toolchains ?? []).join(', ') || '?');
      L.push(`| \`${esc(base(r.path))}\` (${mb(r.size)}) | ${r.role} | ${built} | ${esc(r.signature ? r.signature.signer ?? 'present' : 'unsigned')} | ${what} |`);
    }
    const eng = d.native?.engines?.manifest?.engines;
    if (eng) L.push('', `Engines pinned in \`engines-manifest.json\`: ${Object.entries(eng).map(([k, v]) => `${k} ${esc(/** @type {any} */ (v).version ?? '(none)')}`).join(', ')}.`);
    L.push('');
  }

  // Security posture
  if (map || bins.length) {
    L.push('## Security observations', '');
    const wp = map?.electron?.webPreferences ?? [];
    const flag = (/** @type {string} */ f, /** @type {string} */ v) => wp.filter((/** @type {any} */ w) => w.flag === f && String(w.value) === v).length;
    if (wp.length) L.push(`- webPreferences sites: contextIsolation=true ${flag('contextIsolation', 'true')}, sandbox=true ${flag('sandbox', 'true')}, nodeIntegration=false ${flag('nodeIntegration', 'false')}, nodeIntegration=true ${flag('nodeIntegration', 'true')}, webviewTag=true ${flag('webviewTag', 'true')}.`);
    if (s) L.push(`- IPC sender checks observed: ${s.senderChecks.reduce((/** @type {number} */ n, /** @type {any} */ c) => n + c.count, 0)} (${[...new Set(s.senderChecks.map((/** @type {any} */ c) => c.name))].slice(0, 6).map((n) => `\`${esc(n)}\``).join(', ')}); ${Object.keys(map.electron.ipcChannels).length} channels exist, so coverage cannot be confirmed statically.`);
    if (map?.electron?.dynamicIpc?.length) L.push(`- ${map.electron.dynamicIpc.length} IPC call sites use channel names built at runtime (not resolvable statically).`);
    if (bins.length) {
      const fpBins = bins.filter((/** @type {any} */ r) => ['voyager-helper', 'electron-host', 'native-module'].includes(r.role));
      L.push(`- Authenticode: ${fpBins.filter((/** @type {any} */ r) => r.signature).length} of ${fpBins.length} first-party/host binaries carry a signature (not verified); unsigned include ${fpBins.filter((/** @type {any} */ r) => !r.signature).slice(0, 8).map((/** @type {any} */ r) => `\`${esc(base(r.path))}\``).join(', ')}.`);
      L.push(`- Packed/high-entropy executable sections: ${bins.filter((/** @type {any} */ r) => r.packedSections?.length).length} of ${bins.length} binaries.`);
    }
    if (map?.debugIds?.length || map?.sourceMaps?.length) L.push(`- Build leftovers: ${map.debugIds?.length ?? 0} Sentry debugIds, ${map.sourceMaps?.length ?? 0} sourceMappingURL references; rolldown \`//#region\` markers keep original source paths.`);
    L.push('');
  }

  // Pipeline status
  L.push('## Pipeline status', '', '| stage | status | key notes |', '|---|---|---|');
  for (const e of d.manifest?.entries ?? []) {
    if (e.stage === '05-report') continue;
    L.push(`| ${esc(e.stage)} | ${esc(e.status)} | ${esc((e.notes ?? []).slice(0, 3).join('; '))} |`);
  }
  L.push('');
  return L.join('\n');
}

/**
 * "crates: a, b, ..." for workspaces, "single crate, N source file(s)" otherwise.
 * @param {{ sourceRoots: { root: string, files: number }[], sourceCount: number }} rust
 */
function rustCrates(rust) {
  const ws = rust.sourceRoots.filter((x) => x.root.startsWith('crates/'));
  if (!ws.length) return `single crate, ${rust.sourceCount} source file(s)`;
  return `crates: ${ws.slice(0, 5).map((x) => esc(x.root.slice(7))).join(', ')}${ws.length > 5 ? ', ...' : ''}`;
}

/**
 * Minimal YAML reader for flat `key: value` files such as app-update.yml.
 * @param {string} text
 */
export function parseFlatYaml(text) {
  /** @type {Record<string,string>} */
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = /^([A-Za-z_][\w-]*):\s*(.*?)\s*$/.exec(line);
    if (m) out[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
  return out;
}
